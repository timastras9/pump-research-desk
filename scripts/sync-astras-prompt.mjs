// Copy the Astras agent persona from the Open Astras repo into the Worker (src/astras-prompt.ts).
// Open Astras prompts/astras.md stays the single source; re-run after editing it.
// Usage: node scripts/sync-astras-prompt.mjs [path/to/astras.md]
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';

const src = process.argv[2] ?? `${homedir()}/Astras/projects/astras_os/library/openastra/prompts/astras.md`;
const text = readFileSync(src, 'utf8').trim();
writeFileSync(new URL('../src/astras-prompt.ts', import.meta.url),
  `// Generated by scripts/sync-astras-prompt.mjs from Open Astras prompts/astras.md. Edit that file, then re-run.\nexport const ASTRAS_PERSONA = ${JSON.stringify(text)};\n`);
console.log(`src/astras-prompt.ts <- ${src} (${text.length} chars)`);
